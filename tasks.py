def create_communication_task(agent, upstream_task: Task,
                              destination: str, days: int,
                              is_single_mode: bool = False,
                              weather_context: str = "",
                              plan_b_task: Task | None = None) -> Task:
    """导游沟通者：将行程方案转化为有温度的攻略

    多人模式时传入 plan_b_task，communicator 会等待两个方案都就绪再润色。
    """
    member_part = (
        "- 对每位成员点名回应，让他们觉得自己的需求被记住了\n"
        "   - 逐一回应每个人的偏好和 Hard No\n"
    ) if not is_single_mode else (
        "- 让客户感受到这份攻略是『为你量身定制』的\n"
        "   - 每个安排都解释『为什么适合你』\n"
    )

    if is_single_mode:
        # 单人模式：直接润色单一方案
        body = (
            "上一步已经制定了一份行程方案。"
            "现在请你**以端水大师的身份**，将那份方案转化为一份有温度、高情商的最终旅行攻略。\n\n"
            "写作要求：\n"
            "1. **开头**：用温暖的语气欢迎客户\n"
            f"2. **逐一回应**：\n{member_part}"
            "3. **每日安排**：用讲故事的方式介绍每天的行程，解释每个安排『为什么』适合你\n"
            "4. **结尾**：煽情但不过度，让客户对旅行充满期待\n\n"
            "攻略要有「人情味」，让客户读完觉得：『这份攻略就是为我量身定做的』。"
        )
        expected = (
            "markdown 格式的最终旅行攻略，包含：\n"
            "1. 开篇问候\n"
            f"2. {days} 天行程详解（含安排理由）\n"
            "3. 温馨结尾"
        )
    else:
        # 多人模式：润色两套方案（AB 双方案）+ 解释设计理念
        body = (
            "上一步已经生成了两套独立的行程方案——\n"
            "方案 A「集体妥协路线」和方案 B「动态分头路线」。\n"
            "现在请你**以端水大师的身份**，将这两套方案分别润色成有温度、高情商的最终旅行攻略，"
            "并且**向用户解释『为什么这么排』**。\n\n"
            "**输出结构要求：**\n"
            "1. **开篇（共享，放在最前面）**：用温暖的语气问候大家，"
            "感谢参与和互相包容，引出『为大家准备了两套方案』\n"
            "2. **方案 A 部分**：以 `## 方案 A：集体妥协路线` 开头\n"
            "   - 先写一段 **设计理念**，解释为什么选择集体行动方案"
            "（如：『因为观察到大家虽然节奏不同，但都希望有更多在一起的时间……』）\n"
            f"   - 然后展开 {days} 天的详细安排\n"
            "   - 每天强调餐厅/景点的选择如何兼顾了不同偏好\n"
            "3. **方案 B 部分**：以 `## 方案 B：动态分头路线` 开头\n"
            "   - 先写一段 **设计理念**，解释为什么选择分头行动方案"
            "（如：『因为注意到大家体力悬殊，与其互相迁就都不尽兴，"
            "不如在部分时段各自精彩，晚上再汇合分享……』）\n"
            f"   - 然后展开 {days} 天的详细安排\n"
            "   - 强调汇合点的设计巧思，让分头活动也有『一起旅行』的联结感\n\n"
            f"{member_part}"
            "攻略要有「人情味」，让每个人读完都感觉：『嗯，这个安排有考虑到我』。\n"
            "**重要：** 两套方案都必须点名回应每位成员的需求，确保每个人在每套方案中都能看到自己被照顾到了。"
        )
        expected = (
            "四部分组成的 markdown 攻略：\n"
            "1. 共享开篇问候\n"
            "2. ## 方案 A：集体妥协路线（含设计理念 + 逐日安排）\n"
            "3. ## 方案 B：动态分头路线（含设计理念 + 逐日安排）"
        )

    _weather_block = (
        f"\n\n**天气预报提醒：**\n{weather_context}" if weather_context else ""
    )

    context = [upstream_task]
    if plan_b_task:
        context.append(plan_b_task)

    return Task(
        description=(
            f"目的地：**{destination}**，行程天数：**{days} 天**\n\n"
            f"{body}"
            f"{_weather_block}"
        ),
        expected_output=expected,
        agent=agent,
        context=context,
    )


