"""
Task 定义模块 —— 各 Agent 的任务
支持单/多人模式：单人跳过冲突分析，直接由管家定制攻略
"""

from crewai import Task


def create_analysis_task(agent, preferences_json: str,
                         destination: str, days: int) -> Task:
    """冲突分析师：社会心理学视角的隐性对立分析（多人模式）"""
    return Task(
        description=(
            f"你正在为一次前往 **{destination}** 的 **{days} 天** 旅行做冲突分析。\n\n"
            "你接收到的是一份 JSON 格式的旅行偏好数据，包含多位旅行成员的以下信息：\n"
            "- budget（预算偏好）：省钱党 / 适中派 / 宽裕派\n"
            "- sleep_energy（作息与体力）：早睡早起 / 正常作息 / 夜猫子\n"
            "- intensity_score（旅行节奏）：1=躺平 ~ 10=极限特种兵\n"
            "- wishlist（心愿单与避雷指南）：free text，包含必做事项和 Hard No\n"
            "- is_private（是否保密）：如果为 true，该成员的心愿需要在最终攻略中匿名处理\n\n"
            f"原始数据如下：\n```json\n{preferences_json}\n```\n\n"
            "请运用**社会心理学视角**，逐一分析每位成员的需求，然后对比找出冲突点。\n\n"
            "冲突分析必须包含以下维度，并对每个冲突点分类标注：\n"
            "1️⃣ **预算冲突**：各成员的预算等级差距？省钱党和宽裕派如何平衡？\n"
            "2️⃣ **作息冲突**：起床/睡觉时间是否匹配？早睡早起和夜猫子如何协调？\n"
            "3️⃣ **旅行节奏冲突（隐性对立重点）**：对比所有人的 intensity_score。"
            "如果分差大于 5 分（如一人 2 一人 9），必须作为**红色预警**在报告中突出标注，"
            "并明确建议『分头行动』或『交替安排』作为可能的调解方向。\n"
            "4️⃣ **心愿单冲突（Hard No 重点）**：wishlist 中是否有绝对不可调和的需求？"
            "（如：有人一定要吃辣、有人完全不吃辣；有人要爬山、有人绝对不爬山）\n\n"
            "输出一份 **《冲突与共识分析报告》**（markdown 格式），包含以下三个板块：\n"
            "### 1. 成员需求摘要\n"
            "### 2. 冲突点逐项分析（每个冲突标注 🔴 Hard No / 🟡 可协商 / 🟢 共识）\n"
            "### 3. 协调建议方向（哪些必须拆伙、哪些可以轮流）"
        ),
        expected_output=(
            "markdown 格式的《冲突与共识分析报告》，包含：\n"
            "1. 成员需求摘要表\n"
            "2. 逐项冲突分析（带 🔴🟡🟢 分类标签）\n"
            "3. 协调建议方向（含是否建议分头行动的结论）"
        ),
        agent=agent,
    )


def create_planning_task_a(agent, analysis_task: Task,
                            destination: str, days: int,
                            weather_context: str = "") -> Task:
    """规划师（异步）：方案 A — 帕累托妥协路线（集体行动）"""
    weather_block = (
        f"\n\n**===== 天气预报 ====**\n{weather_context}\n"
        "请根据天气状况动态调整行程：雨天优先安排室内活动（博物馆、美食），"
        "晴天多安排户外景点。每天标注天气提示。\n"
    ) if weather_context else ""

    return Task(
        description=(
            f"目的地：**{destination}**，行程天数：**{days} 天**\n\n"
            "上一步的冲突分析师已经输出了《冲突与共识分析报告》，明确指出了成员之间的"
            " 🔴 Hard No 底线、🟡 可协商空间、🟢 共识点。\n"
            "现在请你**以双轨规划师的身份**，基于那份报告**制定方案 A：帕累托妥协路线**。\n\n"
            "**===== 方案 A：帕累托妥协路线（集体行动）=====**\n"
            "设计逻辑：寻找全员的最大公约数，所有人都在一起行动。\n"
            "- 忽略极端 intensity_score 值，按团队平均节奏（或设定为 5 分）安排\n"
            "- 每天约 3 个主要活动，节奏中等，不赶不闲\n"
            "- 餐饮上轮流满足不同口味：今天吃辣、明天不辣；今天高档、明天平价\n"
            "- 预算上高低搭配：上午免费景点 + 下午付费体验\n"
            "- 充分尊重 🔴 Hard No 底线（如绝对不爬山则取消登山项目）\n"
            "- **『一桌两味』端水餐厅技巧：** 当团队口味冲突时（辣 vs 不辣），优先选择以下能『同台端水』的菜品：\n"
            "   - 烤鱼（双拼口味：青花椒 vs 经典香辣）\n"
            "   - 火锅（奔驰锅/鸳鸯锅：番茄/菌汤 vs 牛油红锅）\n"
            "   - 钵钵鸡（双锅：藤椒 vs 红油）\n"
            "   - 川菜馆的『一菜两做』（如：宫保鸡丁不辣版 + 传统版）\n"
            "   - 陶德砂锅（一锅辣一锅不辣）\n\n"
            "**===== 地理聚合约束（重要）=====**\n"
            "- 同一天的景点必须**按地理区域聚类**，不要安排相距很远的景点\n"
            "- 尽量将同一地理区域（如步行 15 分钟圈 / 驾车 5 公里内）的景点安排在同一天\n"
            "- 如果两个景点驾车超过 30 分钟，除非是跨上午/下午的自然分界，否则应分到不同天\n\n"
            "**===== 交通耗时约束（重要）=====**\n"
            "- 景点之间必须估算交通耗时并计入行程\n"
            "- 标注每天的交通形式建议（步行 / 打车 / 地铁）\n"
            "- **每天有效游览时间**（扣除交通后）建议控制在 6-8 小时\n"
            "- 如果全天交通总耗时超过 2 小时，说明行程太分散，需要减少景点或重新分组\n\n"
            "**===== 行程鲁棒性校验（重要）=====**\n"
            "- 在生成两点之间的交通时，必须留出至少 **30 分钟** 的弹性时间（找路、排队、拍照）\n\n"
            "**===== 通用要求 =====**\n"
            f"- 按 **Day 1 / Day 2 / ... / Day {days}** 逐日编排，共 {days} 天\n"
            "- 每天的活动需注明「推荐理由」和「对谁友好」\n"
            f"- 请推荐 {destination} 的真实景点\n"
            "- 景点名称请用 **加粗** 或 【书名号】 括起来，方便后续地图标注\n"
            "- 你可以使用 DuckDuckGo 搜索工具（`DuckDuckGoSearchRun`）实时查询景点信息、"
            "营业时间、美食推荐等，确保推荐准确可靠\n"
            "- **推荐餐厅必须验证营业状态：** 搜索格式为『餐厅名 + 城市 + 营业状态 2026』。"
            "如果出现『歇业』『暂停营业』『搬迁』字样，立即寻找评分不低于 **4.5 分** 的同类餐厅平替\n"
            "- **搜索频率限制：** 每次任务执行中最多发起 **3 次搜索调用**\n"
            f"{weather_block}"
            "输出时，以 `## 方案 A：集体妥协路线` 开头。"
        ),
        expected_output=(
            f"方案 A markdown 格式的 {days} 日行程"
        ),
        agent=agent,
        async_execution=True,
        context=[analysis_task],
    )


